package com.umg.api.model;

/**
 *
 * @author juanfranciscovaldezlopez
 */
public class Boleto {

    private int id;
    private String codigo;
    private String localidad;
    private String bloque;
    private String fila;
    private Integer numero;
    private double precio;
    private boolean dePie;

    public Boleto() {
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getCodigo() {
        return codigo;
    }

    public void setCodigo(String codigo) {
        this.codigo = codigo;
    }

    public String getLocalidad() {
        return localidad;
    }

    public void setLocalidad(String localidad) {
        this.localidad = localidad;
    }

    public String getBloque() {
        return bloque;
    }

    public void setBloque(String bloque) {
        this.bloque = bloque;
    }

    public String getFila() {
        return fila;
    }

    public void setFila(String fila) {
        this.fila = fila;
    }

    public Integer getNumero() {
        return numero;
    }

    public void setNumero(Integer numero) {
        this.numero = numero;
    }

    public double getPrecio() {
        return precio;
    }

    public void setPrecio(double precio) {
        this.precio = precio;
    }

    @Override
    public String toString() {
        return codigo + " · " + localidad + " · Bloque " + bloque + " · Fila " + fila + " · Asiento " + numero + " · Q" + String.format("%,.2f", precio);
    }

    public boolean isDePie() {
        return dePie;
    }

    public void setDePie(boolean dePie) {
        this.dePie = dePie;
    }
}
